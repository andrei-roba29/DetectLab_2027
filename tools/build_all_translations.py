    for k, v in l_dict.items():
        if k in handled:
            continue
        if k == 'nav_tech' and 'nav_process' in l_dict:
            v_tech = v.replace('\\', '\\\\').replace("'", "\\'").replace('\n', '\\n').replace('\r', '')
