'use strict';
const assert = require('node:assert/strict');
const api = require('./js/apm-next/apm-romania-sites.js');
const sites = require('./js/apm-next/apm-sites.js');
const config = require('./js/apm-next/romania-periods.config.js');
const fixture = require('./test/fixtures/romania-sites.synthetic.json');
const rows = fixture.filter(r=>!r.wkt).map(r=>({object_id:r.object_id,lat:r.lat,lon:r.lon,name:r.attributes.NUMESIT,siruta:r.attributes.SIRUTA,coord_flag:r.attributes.COORD}));
const center = {lat:46,lon:25};
(async()=>{
    const calls=[];
    const client={rpc:async(name,args)=>{calls.push({name,args});return {data:{rows,truncated:true,total_in_area:11,excluded_approximate:1,excluded_unknown_coord:3,excluded_geometry:1},error:null};}};
    let data = await api.createProvider({client}).getSites(center,200);
    assert.equal(calls.length,1);assert.equal(calls[0].name,'apm_sites_within');assert.equal(calls[0].args.p_radius_km,50);
    assert.equal(calls[0].args.p_include_empty_coord,false);
    assert(!data.some(r=>['5','6','7','8'].includes(r.id)));
    assert(data.some(r=>r.id==='3'),'same CODSIT prefix does not merge distinct sites');
    assert(data.some(r=>r.id==='9'),'different names at same location survive');
    assert(!data.some(r=>r.id==='2'),'same normalised name within 5m is duplicate');
    assert.equal(data._meta.duplicate,1); assert.equal(data._meta.excludedType,1);
    assert.equal(data._meta.excludedPosition,1); assert.equal(data._meta.unknownPeriod,1);
    assert.equal(data._meta.truncated,true); assert(data[0].name);
    const filtered=sites.filterSites(data,{center,radiusKm:50}).sites;
    assert(filtered.some(r=>r.id==='9'),'downstream period pool must not spatially merge unlike names');
    config.includeEmptyCoord=true;
    data=await api.createProvider({client}).getSites(center,50);
    assert(data.some(r=>r.id==='6')&&data.some(r=>r.id==='7'));assert(!data.some(r=>r.id==='5'));
    config.includeEmptyCoord=false;
    const before=calls.length;
    const outside=await api.createProvider({client}).getSites({lat:51,lon:10},50);
    assert.equal(calls.length,before);assert.equal(outside.length,0);assert(outside._meta.outsideRomania);assert.match(outside._meta.message,/Romania only.*CSV/);
    await assert.rejects(api.createProvider({client:{rpc:async()=>({error:{message:'not authorised'}})}}).getSites(center,50),/not authorised/);
    await assert.rejects(api.createProvider({client:{rpc:()=>Promise.reject(Error('network error'))}}).getSites(center,50),/network error/);
    await assert.rejects(api.createProvider({timeoutMs:5,client:{rpc:()=>new Promise(()=>{})}}).getSites(center,50),/timed out/);
    await assert.rejects(api.createProvider({client:{rpc:async()=>({data:null})}}).getSites(center,50),/Invalid/);
    assert.equal(api.normaliseName('  AȘEZARE   ROMÂNĂ  '),'asezare romana');
    assert.equal(api.descriptivePart('Așezare de la Roman').text,'asezare');
    for(const name of ['Situl de la Roman','Situl de la Romanesti','Romanesti','Roman','Romania','Asezare de la Biserica']) {
        assert.equal(api.inferPeriod(name).periodLabel,'unknown',name);
        assert.equal(api.isExcludedType(name),false,name);
    }
    assert.equal(api.inferPeriod('Castru roman de la X').periodSource,'name-keyword');
    assert.equal(api.inferPeriod('Castru roman').confidence,'low');
    assert.equal(api.inferPeriod('Asezare eneolitica de la X').periodLabel,'Eneolitic / Chalcolitic');
    assert.equal(api.inferPeriod('Asezare Precucuteni de la X').periodLabel,'Neolitic');
    assert.equal(api.inferPeriod('Asezare noua de la X').periodLabel,'unknown');
    assert(api.areaCrossesBorder({lat:46.8,lon:28},50),'east border, not just bounding-box sides');
    assert(!api.areaCrossesBorder(center,50));
    const pipe=require('./js/apm-next/apm-pipeline.js');
    let seed=123;const rnd=()=>((seed=(seed*1664525+1013904223)>>>0)/4294967296);
    const bg=pipe.sampleBackground({lat:46.8,lon:28},50000,100,[],0,rnd,api.insideRomania);
    assert(bg.length>0&&bg.every(r=>api.insideRomania(r.lat,r.lon)));
    assert.equal(pipe.trainSiteStatus(9).status,'block');assert.equal(pipe.trainSiteStatus(29).status,'warn');
    console.log('PASS Romania provider contract: single RPC/no outside request; errors/timeout; exact/empty COORD; name+5m dedupe/no locality merge; downstream pool; normalisation/descriptive part/Roman place; type exclusions; border-only background; metadata/truncation; thresholds. Synthetic fixtures, not the missing sample.');
})().catch(e=>{config.includeEmptyCoord=false;console.error(e);process.exitCode=1;});
